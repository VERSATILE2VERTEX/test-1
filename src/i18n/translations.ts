export function formatBdt(amount: number, locale: Locale): string {
  const rounded = Math.round(amount);
  const formatted = rounded.toLocaleString('en-IN');
  return locale === 'bn' ? `৳${toBengaliDigits(formatted)}` : `৳${formatted}`;
}

export function formatNum(num: number, locale: Locale, decimals = 1): string {
  const clean = Number.isInteger(num) ? num.toString() : num.toFixed(decimals);
  return locale === 'bn' ? toBengaliDigits(clean) : clean;
}

export function toBengaliDigits(input: string): string {
  const map: Record<string, string> = {
    '0': '০',
    '1': '১',
    '2': '২',
    '3': '৩',
    '4': '৪',
    '5': '৫',
    '6': '৬',
    '7': '৭',
    '8': '৮',
    '9': '৯',
  };
  return input.replace(/[0-9]/g, (d) => map[d] ?? d);
}
